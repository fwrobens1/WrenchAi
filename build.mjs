import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const srcDir = path.join(root, "src");
const outFile = path.join(root, "dist", "WrenchAi.luau");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else if (entry.isFile() && entry.name.endsWith(".luau")) files.push(full);
  }
  return files;
}

function moduleId(file) {
  return path.relative(srcDir, file).split(path.sep).join("/").replace(/\.luau$/, "");
}

const files = await walk(srcDir);
const ids = new Set(files.map(moduleId));
const modules = new Map();
const requirePattern = /require\s*\(\s*(["'])([^"']+)\1\s*\)/g;

for (const file of files) {
  const id = moduleId(file);
  let code = await readFile(file, "utf8");
  code = code.replace(requirePattern, (match, _quote, spec) => {
    if (!spec.startsWith(".")) return match;
    const resolved = path.posix
      .normalize(path.posix.join(path.posix.dirname(id), spec))
      .replace(/\.luau$/, "");
    if (ids.has(resolved)) return `__require(${JSON.stringify(resolved)})`;
    if (ids.has(`${resolved}/init`)) return `__require(${JSON.stringify(`${resolved}/init`)})`;
    throw new Error(`Cannot resolve require("${spec}") in ${id}`);
  });
  modules.set(id, code);
}

const parts = [
  "--!nocheck",
  "-- WrenchAi bundle. Generated by build.mjs from src/. Do not edit by hand.",
  "local __modules = {}",
  "local __cache = {}",
  "local function __require(id)",
  "    local cached = __cache[id]",
  "    if cached ~= nil then return cached end",
  "    local loader = __modules[id]",
  "    if not loader then error('module not found: ' .. tostring(id), 2) end",
  "    local value = loader()",
  "    __cache[id] = value",
  "    return value",
  "end",
];

for (const [id, code] of modules) {
  parts.push(`__modules[${JSON.stringify(id)}] = function()`);
  parts.push(code);
  parts.push("end");
}

parts.push('return __require("main")');
parts.push("");

const output = parts.join("\n");
await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(outFile, output, "utf8");
console.log(
  `Bundled ${modules.size} modules -> ${path.relative(root, outFile)} (${(Buffer.byteLength(output) / 1024).toFixed(1)} KiB)`,
);
